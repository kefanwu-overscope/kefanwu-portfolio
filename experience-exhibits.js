const ATTRIBUTES = {
  _sourcecoordinates: 'sourceCoordinates',
  _objectcoordinates: 'objectCoordinates',
  _attributeopacity: 'attributeOpacity',
  _attributeroughness: 'attributeRoughness',
};

/** Restore the same source shaders used by the project workbench. */
export function prepareRoomExhibit(root, key) {
  const prepared = new Set();
  root.traverse((object) => {
    if (!object.isMesh) return;
    const geometry = object.geometry;
    for (const [semantic, attribute] of Object.entries(ATTRIBUTES)) {
      if (geometry.attributes[semantic]) geometry.setAttribute(attribute, geometry.attributes[semantic]);
    }
    for (const material of Array.isArray(object.material) ? object.material : [object.material]) {
      if (!material || prepared.has(material)) continue;
      prepared.add(material);
      const source = material.userData.roomSourceMaterial;
      if (!source) throw new Error(`Missing source material for room exhibit ${key || root.name}.`);
      material.userData.source = source;
      material.userData.motionUniforms = {};
      if (source.depthWrite !== undefined) material.depthWrite = source.depthWrite;
      if (source.unlit) material.toneMapped = false;
      installSourceMaterial(material, source);
      material.needsUpdate = true;
    }
  });
  root.userData.roomExhibit = key;
  root.userData.roomExhibitSource = 'studio-packed-20260919/sample-0';
  return root;
}
